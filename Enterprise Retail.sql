-- TASK 13
-- POINT-IN-TIME POINT-OF-SALE ANALYTICS

SELECT
    f.TRANSACTION_ID,
    f.TRANSACTION_DATE,

    c.CUSTOMER_ID,
    c.CUSTOMER_NAME,

    c.CITY AS CURRENT_CITY,

    c.HISTORICAL_MEMBERSHIP
        AS MEMBERSHIP_AT_PURCHASE,

    c.SEGMENT
        AS SEGMENT_AT_PURCHASE,

    s.STORE_NAME,

    p.PRODUCT_NAME,

    f.TOTAL_AMOUNT

FROM FACT_SALES f

JOIN DIM_CUSTOMER_HYBRID c
    ON f.CUSTOMER_KEY = c.CUSTOMER_KEY

JOIN DIM_STORE s
    ON f.STORE_KEY = s.STORE_KEY

JOIN DIM_PRODUCT p
    ON f.PRODUCT_KEY = p.PRODUCT_KEY

WHERE c.CUSTOMER_ID = 101

ORDER BY f.TRANSACTION_DATE;





