-- TASK 10
-- MULTI-ATTRIBUTE CUSTOMER UPDATES



-- STEP 1
-- EXPIRE CURRENT RECORDS


UPDATE DIM_CUSTOMER_HYBRID d
SET
    EXPIRY_DATE = DATEADD(DAY, -1, u.EFFECTIVE_DATE),
    IS_CURRENT = FALSE
FROM STG_CUSTOMER_UPDATES u
WHERE d.CUSTOMER_ID = u.CUSTOMER_ID
  AND d.IS_CURRENT = TRUE;



-- STEP 2
-- INSERT NEW ACTIVE VERSIONS


INSERT INTO DIM_CUSTOMER_HYBRID (
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY,
    PREVIOUS_CITY,
    STATE,
    CURRENT_MEMBERSHIP,
    PREVIOUS_MEMBERSHIP,
    HISTORICAL_MEMBERSHIP,
    SEGMENT,
    EFFECTIVE_DATE,
    EXPIRY_DATE,
    IS_CURRENT
)
SELECT
    u.CUSTOMER_ID,
    u.CUSTOMER_NAME,

    -- New/current city
    u.CITY,

    -- Previous city from expired version
    old.CITY AS PREVIOUS_CITY,

    -- New/current state
    u.STATE,

    -- New/current membership
    u.MEMBERSHIP AS CURRENT_MEMBERSHIP,

    -- Previous membership
    old.CURRENT_MEMBERSHIP AS PREVIOUS_MEMBERSHIP,

    -- Historical slice value
    u.MEMBERSHIP AS HISTORICAL_MEMBERSHIP,

    -- SCD2 segment
    u.SEGMENT,

    -- Effective date
    u.EFFECTIVE_DATE,

    -- Active record
    '9999-12-31'::DATE,

    TRUE

FROM STG_CUSTOMER_UPDATES u

JOIN DIM_CUSTOMER_HYBRID old
    ON old.CUSTOMER_ID = u.CUSTOMER_ID
   AND old.IS_CURRENT = FALSE
   AND old.EXPIRY_DATE = DATEADD(DAY, -1, u.EFFECTIVE_DATE);



-- STEP 3
-- SYNCHRONIZE CURRENT PROFILE ATTRIBUTES


UPDATE DIM_CUSTOMER_HYBRID d
SET
    CITY = c.CITY,
    STATE = c.STATE,
    CURRENT_MEMBERSHIP = c.CURRENT_MEMBERSHIP,
    PREVIOUS_MEMBERSHIP = c.PREVIOUS_MEMBERSHIP
FROM DIM_CUSTOMER_HYBRID c
WHERE d.CUSTOMER_ID = c.CUSTOMER_ID
  AND c.IS_CURRENT = TRUE
  AND d.CUSTOMER_ID IN (
      SELECT CUSTOMER_ID
      FROM STG_CUSTOMER_UPDATES
  );



-- VERIFY CUSTOMER HISTORY


SELECT
