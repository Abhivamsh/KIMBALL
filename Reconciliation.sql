CREATE OR REPLACE TABLE SILVER_CLEANED_TRANSACTIONS
(
    TXN_ID VARCHAR,

    TXN_TIME TIMESTAMP,

    MERCHANT_ID NUMBER,

    MERCHANT_NAME VARCHAR,

    MASKED_CARD VARCHAR,

    GROSS_AMOUNT NUMBER(14,2),

    FEE_PCT NUMBER(5,2),

    PROCESSING_FEE NUMBER(14,2),

    NET_SETTLEMENT_AMOUNT NUMBER(14,2),

    STATUS VARCHAR
);



INSERT INTO SILVER_CLEANED_TRANSACTIONS
(
    TXN_ID,

    TXN_TIME,

    MERCHANT_ID,

    MERCHANT_NAME,

    MASKED_CARD,

    GROSS_AMOUNT,

    FEE_PCT,

    PROCESSING_FEE,

    NET_SETTLEMENT_AMOUNT,

    STATUS
)

SELECT

    RAW_DATA:txn_id::VARCHAR,

    RAW_DATA:txn_time::TIMESTAMP,

    RAW_DATA:merchant_id::NUMBER,

    RAW_DATA:merchant_name::VARCHAR,


    /* CARD MASKING */

    'XXXX-XXXX-XXXX-' ||
    RIGHT(
        RAW_DATA:card_number::VARCHAR,
        4
    ) AS MASKED_CARD,


  

    RAW_DATA:amount::NUMBER(14,2),


    

    RAW_DATA:fee_pct::NUMBER(5,2),


   

    ROUND(
        RAW_DATA:amount::NUMBER(14,2)
        *
        (
            RAW_DATA:fee_pct::NUMBER(5,2)
            / 100
        ),
        2
    ) AS PROCESSING_FEE,


   

    ROUND(
        RAW_DATA:amount::NUMBER(14,2)
        -
        (
            RAW_DATA:amount::NUMBER(14,2)
            *
            (
                RAW_DATA:fee_pct::NUMBER(5,2)
                / 100
            )
        ),
        2
    ) AS NET_SETTLEMENT_AMOUNT,


   

    RAW_DATA:status::VARCHAR

FROM BRONZE_PAYMENT_PAYLOADS;




SELECT *

FROM SILVER_CLEANED_TRANSACTIONS

ORDER BY TXN_ID;



SELECT
    COUNT(*) AS SILVER_RECORD_COUNT
FROM SILVER_CLEANED_TRANSACTIONS;




CREATE OR REPLACE TABLE GOLD_MERCHANT_SETTLEMENTS
(
    MERCHANT_ID NUMBER,

    MERCHANT_NAME VARCHAR,

    TOTAL_APPROVED_GROSS NUMBER(14,2),

    TOTAL_GATEWAY_FEES NUMBER(14,2),

    TOTAL_NET_PAYOUT NUMBER(14,2),

    APPROVED_COUNT NUMBER
);



INSERT INTO GOLD_MERCHANT_SETTLEMENTS
(
    MERCHANT_ID,

    MERCHANT_NAME,

    TOTAL_APPROVED_GROSS,

    TOTAL_GATEWAY_FEES,

    TOTAL_NET_PAYOUT,

    APPROVED_COUNT
)

SELECT

    MERCHANT_ID,

    MERCHANT_NAME,

    SUM(GROSS_AMOUNT) AS TOTAL_APPROVED_GROSS,

    SUM(PROCESSING_FEE) AS TOTAL_GATEWAY_FEES,

