SELECT

    SUM(
        RAW_DATA:amount::NUMBER(14,2)
    ) AS BRONZE_GROSS_SUM

FROM BRONZE_PAYMENT_PAYLOADS;


SELECT

    SUM(GROSS_AMOUNT) AS SILVER_GROSS_SUM

FROM SILVER_CLEANED_TRANSACTIONS;



SELECT

    SUM(TOTAL_APPROVED_GROSS) AS GOLD_GROSS_SUM

FROM GOLD_MERCHANT_SETTLEMENTS;


WITH BRONZE AS
(
    SELECT

        SUM(
            RAW_DATA:amount::NUMBER(14,2)
        ) AS GROSS_SUM

    FROM BRONZE_PAYMENT_PAYLOADS
),

SILVER AS
(
    SELECT

        SUM(GROSS_AMOUNT) AS GROSS_SUM

    FROM SILVER_CLEANED_TRANSACTIONS
),

GOLD AS
(
    SELECT

        SUM(TOTAL_APPROVED_GROSS) AS GROSS_SUM

    FROM GOLD_MERCHANT_SETTLEMENTS
)

SELECT

    BRONZE.GROSS_SUM AS BRONZE_GROSS_SUM,

    SILVER.GROSS_SUM AS SILVER_GROSS_SUM,

    GOLD.GROSS_SUM AS GOLD_GROSS_SUM,

    CASE

        WHEN BRONZE.GROSS_SUM = SILVER.GROSS_SUM

        THEN TRUE

        ELSE FALSE

    END AS DATA_MATCH_FLAG

FROM BRONZE

CROSS JOIN SILVER

CROSS JOIN GOLD;



SELECT

    'BRONZE' AS LAYER,

    COUNT(*) AS RECORD_COUNT,

    SUM(
        RAW_DATA:amount::NUMBER(14,2)
    ) AS GROSS_TOTAL

FROM BRONZE_PAYMENT_PAYLOADS

UNION ALL

SELECT

    'SILVER' AS LAYER,

    COUNT(*) AS RECORD_COUNT,

    SUM(GROSS_AMOUNT) AS GROSS_TOTAL

FROM SILVER_CLEANED_TRANSACTIONS

UNION ALL

SELECT

    'GOLD' AS LAYER,

    SUM(APPROVED_COUNT) AS RECORD_COUNT,

    SUM(TOTAL_APPROVED_GROSS) AS GROSS_TOTAL

FROM GOLD_MERCHANT_SETTLEMENTS;



SELECT

    MERCHANT_ID,

    MERCHANT_NAME,

    TOTAL_APPROVED_GROSS,

    TOTAL_GATEWAY_FEES,

    TOTAL_NET_PAYOUT,

    APPROVED_COUNT

FROM GOLD_MERCHANT_SETTLEMENTS

ORDER BY TOTAL_NET_PAYOUT DESC;
