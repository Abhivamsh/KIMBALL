SELECT
    C.CUSTOMER_ID,
    CONCAT(C.FIRST_NAME, ' ', C.LAST_NAME) AS CUSTOMER_NAME,
    SUM(O.TOTAL_AMOUNT) AS TOTAL_SPENT
FROM CUSTOMERS C
JOIN ORDERS O
    ON C.CUSTOMER_ID = O.CUSTOMER_ID
GROUP BY
    C.CUSTOMER_ID,
    C.FIRST_NAME,
    C.LAST_NAME
ORDER BY TOTAL_SPENT DESC;

SELECT
    C.CUSTOMER_ID,
    CONCAT(C.FIRST_NAME,' ',
    C.LAST_NAME) AS Customer_Name,
    SUM(O.TOTAL_AMOUNT) AS TOTAL_SPENT
FROM CUSTOMERS C
JOIN ORDERS O
ON C.CUSTOMER_ID = O.CUSTOMER_ID
GROUP BY
    C.CUSTOMER_ID,
    C.FIRST_NAME,
    C.LAST_NAME
ORDER BY TOTAL_SPENT DESC
LIMIT 1;

SELECT SUM(TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM ORDERS;

SELECT
    F.CATEGORY,
    SUM(O.TOTAL_AMOUNT) AS REVENUE
FROM ORDERS O
JOIN FOODITEMS F
ON O.FOOD_ID = F.FOOD_ID
GROUP BY F.CATEGORY
ORDER BY REVENUE DESC;

SELECT
    STATUS AS ORDER_STATUS,
    SUM(TOTAL_AMOUNT) AS REVENUE
FROM ORDERS
GROUP BY STATUS
ORDER BY REVENUE DESC;

SELECT
    C.CUSTOMER_ID,
    CONCAT(C.FIRST_NAME, ' ', C.LAST_NAME) AS CUSTOMER_NAME,
    SUM(O.TOTAL_AMOUNT) AS TOTAL_SPENT
FROM CUSTOMERS C
JOIN ORDERS O
    ON C.CUSTOMER_ID = O.CUSTOMER_ID
GROUP BY
    C.CUSTOMER_ID,
    C.FIRST_NAME,
    C.LAST_NAME
ORDER BY TOTAL_SPENT DESC
LIMIT 3;


SELECT
    C.CUSTOMER_ID,
    CONCAT(C.FIRST_NAME, ' ', C.LAST_NAME) AS CUSTOMER_NAME,
    COUNT(O.ORDER_ID) AS ORDERS_PLACED
FROM ORDERS O
JOIN CUSTOMERS C
    ON C.CUSTOMER_ID = O.CUSTOMER_ID
GROUP BY
    C.CUSTOMER_ID,
    C.FIRST_NAME,
    C.LAST_NAME
ORDER BY ORDERS_PLACED DESC;

SELECT *
FROM ORDERS
WHERE STATUS = 'Delivered';

SELECT
    O.ORDER_ID,
    CONCAT(C.FIRST_NAME, ' ', C.LAST_NAME) AS CUSTOMER_NAME,
    O.ORDER_DATE,
    O.STATUS,
    O.TOTAL_AMOUNT
FROM ORDERS O
JOIN CUSTOMERS C
    ON C.CUSTOMER_ID = O.CUSTOMER_ID
WHERE O.ORDER_DATE > '2026-07-12'
ORDER BY O.ORDER_DATE;

CREATE OR REPLACE VIEW CUSTOMER_SALES_REPORT AS
SELECT
    C.CUSTOMER_ID,
    CONCAT(C.FIRST_NAME, ' ', C.LAST_NAME) AS CUSTOMER_NAME,
    SUM(O.TOTAL_AMOUNT) AS TOTAL_SPENT
FROM CUSTOMERS C
JOIN ORDERS O
    ON C.CUSTOMER_ID = O.CUSTOMER_ID
GROUP BY
    C.CUSTOMER_ID,
    C.FIRST_NAME,
    C.LAST_NAME;

SELECT *
FROM CUSTOMER_SALES_REPORT;

SELECT *
FROM CUSTOMER_SALES_REPORT
ORDER BY TOTAL_SPENT DESC;