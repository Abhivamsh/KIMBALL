AUTO_SUSPEND=60
AUTO_RESUME=TRUE;

CREATE OR REPLACE DATABASE CUSTOMER_SALES_DB;

CREATE OR REPLACE SCHEMA SALES_SCHEMA;

USE WAREHOUSE SALES_WH;

USE DATABASE CUSTOMER_SALES_DB;

USE SCHEMA SALES_SCHEMA;

CREATE OR REPLACE FILE FORMAT CSV_FILE_FORMAT
TYPE = CSV
FIELD_DELIMITER = ','
SKIP_HEADER = 1;



CREATE STAGE IF NOT EXISTS SALES_STAGE FILE_FORMAT = CSV_FILE_FORMAT;



CREATE OR REPLACE TABLE CUSTOMERS
(
    CUSTOMER_ID INT,
    FIRST_NAME VARCHAR(50),
    LAST_NAME VARCHAR(50),
    EMAIL VARCHAR(100),
    PHONE VARCHAR(20),
    ADDRESS VARCHAR(100)
);

CREATE OR REPLACE TABLE FOODITEMS
(
    FOOD_ID INT,
    NAME VARCHAR(100),
    PRICE NUMBER(10,2),
    CATEGORY VARCHAR(50),
    AVAILABILITY VARCHAR(20)
);

CREATE OR REPLACE TABLE ORDERS
(
    ORDER_ID INT,
    CUSTOMER_ID INT,
    FOOD_ID INT,
    QUANTITY INT,
    ORDER_DATE TIMESTAMP,
    STATUS VARCHAR(20),
    TOTAL_AMOUNT NUMBER(10,2)
);

