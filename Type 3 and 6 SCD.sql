-- FINAL VALIDATION


SELECT
    (SELECT COUNT(*) FROM DIM_CUSTOMER_SCD3)
        AS SCD_TYPE_3_RECORD_COUNT,

    (SELECT COUNT(*) FROM DIM_CUSTOMER_SCD6)
        AS SCD_TYPE_6_RECORD_COUNT,

    (SELECT COUNT(*)
     FROM DIM_CUSTOMER_SCD6
     WHERE IS_CURRENT = TRUE)
        AS SCD_TYPE_6_CURRENT_RECORD_COUNT,

    (SELECT COUNT(*)
     FROM DIM_CUSTOMER_SCD6
     WHERE IS_CURRENT = FALSE)
