-- TASK 16 — TYPE 3 VS TYPE 6 COMPARISON


-- SCD TYPE 3
--
-- Current Value       YES
-- Previous Value      YES
-- Historical Rows     NO
-- Effective Date      NO
-- Expiry Date         NO
-- IS_CURRENT          NO
--
--
-- SCD TYPE 6
--
-- Current Value       YES
-- Previous Value      YES
-- Historical Rows     YES
-- Effective Date      YES
-- Expiry Date         YES
-- IS_CURRENT          YES


-- TASK 17 — RECORD COUNT VALIDATION



