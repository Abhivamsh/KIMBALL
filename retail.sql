SELECT
    C.CUSTOMER_NAME,
    SUM(S.TOTAL_AMOUNT) AS TOTAL_SPENT,
    RANK() OVER(
        ORDER BY SUM(S.TOTAL_AMOUNT) DESC
    ) AS CUSTOMER_RANK
FROM CUSTOMERS C
JOIN SALES S
    ON C.CUSTOMER_ID = S.CUSTOMER_ID
GROUP BY
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME
ORDER BY CUSTOMER_RANK;

SELECT
    SALE_ID,
    CUSTOMER_ID,
    TOTAL_AMOUNT,
    ROW_NUMBER() OVER(
        ORDER BY TOTAL_AMOUNT DESC
    ) AS SALE_NUMBER
FROM SALES;

SELECT
    SALE_ID,
    TOTAL_AMOUNT,
    SUM(TOTAL_AMOUNT) OVER() AS TOTAL_REVENUE
FROM SALES;

SELECT
    SALE_ID,
    TOTAL_AMOUNT,
    AVG(TOTAL_AMOUNT) OVER() AS AVERAGE_SALE
FROM SALES;

WITH customer_sales AS
(
    SELECT
        CUSTOMER_ID,
        SUM(TOTAL_AMOUNT) AS TOTAL_SPENT
    FROM SALES
    GROUP BY CUSTOMER_ID
)
SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    CS.TOTAL_SPENT
FROM customer_sales CS
JOIN CUSTOMERS C
    ON CS.CUSTOMER_ID = C.CUSTOMER_ID
ORDER BY CS.TOTAL_SPENT DESC;

CREATE OR REPLACE VIEW SALES_REPORT AS
SELECT
    S.SALE_ID,
    C.CUSTOMER_NAME,
    P.PRODUCT_NAME,
    B.BRANCH_NAME,
    S.QUANTITY,
    S.SALE_DATE,
    S.TOTAL_AMOUNT
FROM SALES S
JOIN CUSTOMERS C
    ON S.CUSTOMER_ID = C.CUSTOMER_ID
JOIN PRODUCTS P
    ON S.PRODUCT_ID = P.PRODUCT_ID
JOIN BRANCHES B
    ON S.BRANCH_ID = B.BRANCH_ID;

    SELECT *
FROM SALES_REPORT;

CREATE OR REPLACE MATERIALIZED VIEW TOP_CUSTOMERS AS
SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    SUM(S.TOTAL_AMOUNT) AS TOTAL_SPENT
FROM CUSTOMERS C
JOIN SALES S
    ON C.CUSTOMER_ID = S.CUSTOMER_ID
GROUP BY
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME;

SELECT *
FROM TOP_CUSTOMERS
ORDER BY TOTAL_SPENT DESC
LIMIT 3;


