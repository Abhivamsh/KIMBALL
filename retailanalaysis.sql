CREATE OR REPLACE WAREHOUSE STAR_SCHEMA_WH
WAREHOUSE_SIZE='XSMALL'
AUTO_SUSPEND = 60
AUTO_RESUME= TRUE; 

CREATE OR REPLACE DATABASE STAR_SCHEMA_DB;

CREATE OR REPLACE SCHEMA STAR_SCHEMA_DB.RETAIL_SCHEMA;

USE WAREHOUSE STAR_SCHEMA_WH;
USE DATABASE STAR_SCHEMA_DB;
USE SCHEMA RETAIL_SCHEMA;

CREATE OR REPLACE FILE FORMAT STAR_CSV_FORMAT
TYPE = CSV
FIELD_DELIMITER = ','
SKIP_HEADER = 1
FIELD_OPTIONALLY_ENCLOSED_BY = '"';

CREATE OR REPLACE STAGE STAR_SCHEMA_STAGE
FILE_FORMAT = STAR_CSV_FORMAT;

LIST @STAR_SCHEMA_STAGE; 

CREATE OR REPLACE TABLE DIM_CUSTOMER
(
    CUSTOMER_ID INT,
    CUSTOMER_NAME VARCHAR(100),
    CITY VARCHAR(50),
    STATE VARCHAR(50),
    MEMBERSHIP VARCHAR(20)
);

CREATE OR REPLACE TABLE DIM_PRODUCT
(
    PRODUCT_ID INT,
    PRODUCT_NAME VARCHAR(100),
    CATEGORY VARCHAR(50),
    BRAND VARCHAR(50),
    PRICE NUMBER(10,2)
);

CREATE OR REPLACE TABLE DIM_BRANCH
(
    BRANCH_ID INT,
    BRANCH_NAME VARCHAR(100),
    CITY VARCHAR(50),
    STATE VARCHAR(50),
    REGION VARCHAR(30),
    MANAGER_NAME VARCHAR(100)
);
CREATE OR REPLACE TABLE DIM_DATE
(
    DATE_ID INT,
    DATE DATE,
    DAY INT,
    DAY_NAME VARCHAR(20),
    WEEK_NO INT,
    MONTH VARCHAR(20),
    QUARTER VARCHAR(10),
    YEAR INT,
    IS_WEEKEND VARCHAR(5)
);

CREATE OR REPLACE TABLE FACT_SALES
(
SALE_ID INT,
CUSTOMER_ID INT,
PRODUCT_ID INT,
BRANCH_ID INT,
DATE_ID  INT,
QUANTITY INT,
TOTAL_AMOUNT DECIMAL(12,2)

)

